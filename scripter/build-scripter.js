// build-scripter.js — bundle Crux into one script for Logic's Scripter (MIDI FX).
//
//   node scripter/build-scripter.js [program.crux]
//
// Writes dist/crux-scripter.js: the Crux program on top (edit it there, in
// Scripter's editor), then ohm-js and dist/crux.cjs wrapped so their names stay
// private, then scripter/player.js. Run `npm run build` first if src/ changed.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');

const programFile = process.argv[2];
const program = programFile
  ? fs.readFileSync(programFile, 'utf8')
  : `// Edit me, then press Run Script. timeScale 1 is a quarter note, steps are C major degrees.
subject = [0, 2, 4, 5, 7, 5, 4, 2]
subject
!8
subject * [4]
`;
if (program.includes('`')) throw new Error('the Crux program cannot contain a backtick (`)');
const version = JSON.parse(read('package.json')).version;

const out = `// Crux ${version} for Logic Scripter — generated by scripter/build-scripter.js; edit the program below.
// Put Scripter in a track's MIDI FX slot, paste this whole file into its
// Script Editor, press Run Script, and press Play. One voice per section (\`!\`).

var CRUX = String.raw\`
${program.trim()}
\`;

// ─── everything below is generated ─────────────────────────────────────────
var globalThis = (typeof globalThis !== 'undefined') ? globalThis : this;
var console = (typeof console !== 'undefined') ? console
  : { log: function () { Trace([].join.call(arguments, ' ')); }, warn: function () { Trace([].join.call(arguments, ' ')); }, error: function () { Trace([].join.call(arguments, ' ')); } };

// ohm-js ${JSON.parse(read('node_modules/ohm-js/package.json')).version} (MIT) and Crux, in their own scope; they leave globalThis.golden.
(function () {
var require = undefined, module = undefined, exports = undefined, define = undefined, window = undefined;
${read('node_modules/ohm-js/dist/ohm.min.js')}
;
${read('dist/crux.cjs')}
}).call(globalThis);
var golden = globalThis.golden;

${read('scripter/player.js')}
`;

fs.mkdirSync(path.join(root, 'dist'), { recursive: true });
fs.writeFileSync(path.join(root, 'dist/crux-scripter.js'), out);
console.log('wrote dist/crux-scripter.js', Math.round(out.length / 1024) + ' KB');
